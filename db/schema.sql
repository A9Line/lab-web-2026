-- ЛР9. Схема БД: вывоз лабораторных отходов
-- Таблицы и поля как в docs/data-model.md (ЛР2), имена в snake_case.
-- Скрипт можно запускать повторно: в начале удаляются только наши таблицы.

DROP TABLE IF EXISTS waste_requests CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS waste_types CASCADE;
DROP TABLE IF EXISTS laboratories CASCADE;

-- справочник лабораторий
CREATE TABLE laboratories (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

-- справочник типов отходов
CREATE TABLE waste_types (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    hazard_class integer NOT NULL CHECK (hazard_class BETWEEN 1 AND 5)
);

-- пользователи: заведующий, инженер, эколог
-- password_hash заполним в ЛР11, когда появится вход
CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         text NOT NULL UNIQUE,
    full_name     text NOT NULL,
    role          text NOT NULL CHECK (role IN ('LabHead', 'Engineer', 'EcoResponsible')),
    password_hash text NULL
);

-- заявки на вывоз отходов (главный объект)
CREATE TABLE waste_requests (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number             text NOT NULL UNIQUE,
    title              text NOT NULL CHECK (char_length(title) BETWEEN 5 AND 80),
    description        text NOT NULL CHECK (char_length(description) BETWEEN 10 AND 500),
    status             text NOT NULL DEFAULT 'New'
                       CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    laboratory_id      integer NOT NULL REFERENCES laboratories (id),
    waste_type_id      integer NOT NULL REFERENCES waste_types (id),
    created_by_user_id integer NOT NULL REFERENCES users (id),
    assignee_user_id   integer NULL REFERENCES users (id),
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now()
);

-- зачем: фильтр списка по статусу (WHERE status = 'New') и подсчёт по статусам
CREATE INDEX waste_requests_status_idx ON waste_requests (status);

-- зачем: JOIN с laboratories и выборка заявок одной лаборатории
CREATE INDEX waste_requests_laboratory_id_idx ON waste_requests (laboratory_id);

-- зачем: список «мои заявки» для инженера (WHERE assignee_user_id = ...)
CREATE INDEX waste_requests_assignee_user_id_idx ON waste_requests (assignee_user_id);
